-- Friends joining somebody's delivery.
--
-- Points at the order whose link they opened. It is deliberately NOT the group
-- machinery: a group renumbers its orders (#1042 becomes #1042a), and the
-- leader has already been told what to type in their transfer. Nobody's
-- reference may change because somebody else joined. Every order keeps its own
-- number, its own narration and its own payment; only the delivery is shared,
-- which is the only thing being shared in real life too.
alter table orders add column if not exists shared_with uuid references orders(id) on delete set null;
create index if not exists orders_shared_idx on orders (shared_with);

-- A shared delivery that friends are still adding to.
--
-- `closes_at` is when it stops taking people: fifteen minutes from the moment
-- it was started, and never past the run's own cut off. Until then nobody has
-- a total, because the delivery fee depends on how many end up in the car and
-- how much they order between them. `closed_at` is when it actually happened,
-- by the leader tapping close or by the clock running out.
--
-- Nobody is quoted anything before the close, which is the whole point: a
-- figure that has not been given out cannot change underneath somebody.
alter table order_groups add column if not exists closes_at timestamptz;
alter table order_groups add column if not exists closed_at timestamptz;
-- Whose job it is to pay, when the group decided one person pays for all.
alter table order_groups add column if not exists payer_phone text;
create index if not exists order_groups_closing_idx on order_groups (closes_at)
  where closed_at is null;

-- "I have finished ordering", from one person in a shared delivery.
--
-- A group closes on whichever comes first: everybody in it has said they are
-- done, the person who started it closes it by hand, or the fifteen minutes
-- runs out. Waiting on a clock when everyone is already finished would be
-- fifteen minutes of nobody being able to pay.
alter table orders add column if not exists done_at timestamptz;

-- Same day delivery, which is a different business from the batched runs.
--
-- A run carries everybody in one car and is cheap because of it. Same day is a
-- car going out for one order, at a time the customer picked, so it is priced
-- on its own ladder and kept out of the run list customers choose from.
--
-- `kind` is what keeps them apart. Every batch that already exists is a run,
-- which is why it defaults to one and why nothing changes the day this runs.
alter table batches add column if not exists kind text not null default 'run'
  check (kind in ('run', 'same_day'));
-- The time the customer asked for. Only ever set on a same day delivery.
alter table batches add column if not exists deliver_at timestamptz;
create index if not exists batches_kind_idx on batches (kind, run_date desc);

-- The two same day ladders, so the prices can be changed without a deploy,
-- exactly as the batched bands already can. Empty means the built in ones.
alter table settings add column if not exists same_day_bands text not null default '';
-- Switch same day off entirely on a day you cannot do it.
alter table settings add column if not exists same_day_on text not null default '';
-- What being inside the five hours adds, on every step of the ladder.
alter table settings add column if not exists same_day_urgent_extra text not null default '';
-- The hours of the day a delivery can be asked for, so extending the day is a
-- change of mind rather than a deploy, and so nothing in the wording has to
-- name an hour that might later be wrong.
alter table settings add column if not exists same_day_first_hour text not null default '';
alter table settings add column if not exists same_day_last_hour  text not null default '';

-- The token behind a group link.
--
-- A link has to exist the moment somebody thinks of sharing it, before they
-- have typed a name or picked a run, so it cannot hang off an order. It is a
-- random string made in the browser: the first person in the party to check
-- out creates the group under it, and everybody else who checked out with the
-- same token lands in that same group.
--
-- Unique, so two friends checking out in the same second cannot each make
-- their own group and end up in separate cars. Only ever set on a group
-- started from a link, which is why the index skips the nulls.
alter table order_groups add column if not exists party_token text;
create unique index if not exists order_groups_party_idx
  on order_groups (party_token) where party_token is not null;

-- Whether this phone wants to hear about deals. Order news is not optional:
-- it is about food somebody has already paid for.
alter table push_devices add column if not exists deals boolean not null default true;





-- Food put into a shared delivery, before there is an order for it.
--
-- In a group nobody has a delivery fee until the group closes, because it
-- depends on who else turns up. An order was still made at checkout, which
-- meant a real order, with a real number, sitting at a fee of nothing, for a
-- car nobody could buy for yet. If the group was then abandoned that number
-- was spent on nothing.
--
-- So the food waits here instead. One row per person while the group fills,
-- carrying exactly what checkout was told. When the group closes each row
-- becomes a real order, priced then, once and for all.
--
-- Nothing about price is kept here. The lines are item ids and quantities,
-- exactly as the cart posts them, and everything is priced from the menu at
-- the moment the order is made, as it always has been.
create table if not exists group_carts (
  id             uuid primary key default gen_random_uuid(),
  group_id       uuid not null references order_groups(id) on delete cascade,
  phone          text not null,
  name           text not null,
  hostel         text not null default '',
  /** What they chose: menu_item_id, qty and any option ids. */
  lines          jsonb not null,
  payment_method text not null default 'transfer',
  customer_note  text not null default '',
  coupon         text not null default '',
  /** Set when they say they have finished adding. */
  done_at        timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  -- One person, one place in the car. Checking out again replaces what they
  -- had rather than putting them in twice.
  unique (group_id, phone)
);
create index if not exists group_carts_group_idx on group_carts (group_id);
alter table group_carts enable row level security;


-- The shared cart, reshaped: you join by name, not by checking out.
--
-- Joining a group and ordering are two moments, and squashing them into one
-- asked for a phone number and a block before anybody had decided anything.
-- So a seat in the car is taken by name, keyed on a token this browser keeps,
-- and the number and block are filled in afterwards while everybody waits for
-- the last person to finish.
alter table group_carts add column if not exists member_token text;
alter table group_carts add column if not exists finalised_at timestamptz;
alter table group_carts alter column phone drop not null;
alter table group_carts alter column phone set default '';
alter table group_carts alter column lines set default '[]'::jsonb;

-- The seat belongs to the browser that took it, not to a number nobody has
-- given yet. Anybody already keyed by phone keeps their seat.
update group_carts set member_token = id::text where member_token is null;

do $seat_per_browser$
begin
  if exists (
    select 1 from pg_constraint where conname = 'group_carts_group_id_phone_key'
  ) then
    alter table group_carts drop constraint group_carts_group_id_phone_key;
  end if;
end $seat_per_browser$;

create unique index if not exists group_carts_seat_idx
  on group_carts (group_id, member_token);


-- A restaurant link somebody can read.
--
-- /r/a4e5104f-a815-49c8-b491-cb07325ddec7 is not a link anybody pastes into
-- a group chat. /r/dominos-pizza is. The id stays the key and old links keep
-- working; this is only a second way in.
alter table restaurants add column if not exists slug text;

-- Made from the name, once, for everything that has not got one. Anything
-- already set is left alone, because a link that has been sent out must not
-- change under it.
update restaurants
set slug = base.candidate
from (
  select
    id,
    case
      when row_number() over (partition by cleaned order by sort_order, name) = 1
        then cleaned
      else cleaned || '-' ||
           row_number() over (partition by cleaned order by sort_order, name)::text
    end as candidate
  from (
    select
      id,
      name,
      sort_order,
      -- Apostrophes go rather than becoming hyphens: Domino's Pizza is
      -- dominos-pizza, not domino-s-pizza.
      trim(both '-' from
        regexp_replace(
          regexp_replace(lower(name), '[''’`]', '', 'g'),
          '[^a-z0-9]+', '-', 'g'
        )
      ) as cleaned
    from restaurants
  ) tidy
  where cleaned <> ''
) base
where restaurants.id = base.id
  and (restaurants.slug is null or restaurants.slug = '');

create unique index if not exists restaurants_slug_idx
  on restaurants (slug) where slug is not null and slug <> '';

