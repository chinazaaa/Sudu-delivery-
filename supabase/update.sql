-- A restaurant link somebody can read.
--
-- /r/a4e5104f-a815-49c8-b491-cb07325ddec7 is not a link anybody pastes into
-- a group chat. /r/dominos-pizza is. The id stays the key and old links keep
-- working; this is only a second way in.
alter table restaurants add column if not exists slug text;

-- Made from the name, once, for everything that has not got one. Anything
-- already set is left alone, because a link that has been sent out must not
-- change under it.
update restaurants
set slug = base.candidate
from (
  select
    id,
    case
      when row_number() over (partition by cleaned order by sort_order, name) = 1
        then cleaned
      else cleaned || '-' ||
           row_number() over (partition by cleaned order by sort_order, name)::text
    end as candidate
  from (
    select
      id,
      name,
      sort_order,
      -- Apostrophes go rather than becoming hyphens: Domino's Pizza is
      -- dominos-pizza, not domino-s-pizza.
      trim(both '-' from
        regexp_replace(
          regexp_replace(lower(name), '[''’`]', '', 'g'),
          '[^a-z0-9]+', '-', 'g'
        )
      ) as cleaned
    from restaurants
  ) tidy
  where cleaned <> ''
) base
where restaurants.id = base.id
  and (restaurants.slug is null or restaurants.slug = '');

create unique index if not exists restaurants_slug_idx
  on restaurants (slug) where slug is not null and slug <> '';


-- What the food actually cost at the counter.
--
-- Profit was worked out as what customers paid for food minus what customers
-- paid for food, which assumes every plate cost exactly the menu price. It
-- often does not: turn up in person often enough and a counter gives it to
-- you for less, and that discount is the shop's margin, sitting invisible.
--
-- Zero means nothing was typed in and the menu prices stand, so nothing
-- changes for any run where this is left alone.
alter table batches add column if not exists food_spend int not null default 0;


-- What each thing actually cost at the counter.
--
-- The menu price is what the customer paid, not what the shop paid. Turn up
-- in person and a counter often charges less, sometimes more, and profit was
-- being worked out as though it were always exactly the same. This is where
-- the real figure goes, one row per thing bought on one run.
--
-- Kept per line rather than as a single total so it can be corrected later
-- without retyping the lot, and so the run sheet can show what moved.
create table if not exists counter_spend (
  id         uuid primary key default gen_random_uuid(),
  batch_id   uuid not null references batches(id) on delete cascade,
  /** Restaurant, item and choices, as the counter list groups them. */
  line_key   text not null,
  /** What was handed over for that line in total, not per unit. */
  paid       int not null default 0 check (paid >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (batch_id, line_key)
);
create index if not exists counter_spend_batch_idx on counter_spend (batch_id);
alter table counter_spend enable row level security;

-- What the customer handed back when the counter charged well over the menu.
--
-- Asking somebody for the difference on a plate that went up two hundred
-- naira is not worth the conversation, but on a big gap it is, and when they
-- pay it the shop is not out of pocket. Without somewhere to put it, that
-- money never reached the books and the run read as a loss it had not made.
alter table counter_spend add column if not exists recovered int not null default 0
  check (recovered >= 0);

-- Which restaurants a code works on. A code like AWOF is a deal with one
-- kitchen, not a discount on anything the shop carries, so it has to hold to
-- that kitchen and no other.
--
-- With no rows here it works on anything, which is what every code written
-- before today is. With rows, the whole cart has to come from those places:
-- a code for Domino's on a cart of Domino's and a shawarma is a code being
-- spent on the shawarma too, and the deal does not cover that.
create table if not exists coupon_restaurants (
  coupon_code   text not null references coupons(code) on delete cascade,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  primary key (coupon_code, restaurant_id)
);
create index if not exists coupon_restaurants_place_idx
  on coupon_restaurants (restaurant_id);
alter table coupon_restaurants enable row level security;


-- Getting there and back, apart from the fuel.
--
-- A run is a keke to the junction, a bike with the bags, sometimes a car when
-- there is too much to carry. That is not fuel and it is not the driver, and
-- putting it under Anything else meant the one cost that changes most from
-- run to run was buried in a box with the bags and the gate fee.
alter table batches add column if not exists transport_cost int not null default 0;


-- A promotion: a code that needs no typing, and sets the delivery rather than
-- taking money off it.
--
-- "Order Domino's, delivery is 2,000" is not a discount on the ladder, it is
-- a different price entirely: five items or one, it is 2,000. And nobody
-- types anything, because a price nobody has to know a word for is a price
-- everybody gets.
--
-- It lives with the codes rather than beside them because it is the same
-- thing in every other respect: one restaurant, chosen runs, an expiry, a cap
-- on how many orders it is good for, an on and off switch, and the strip
-- along the top that reads the offer rather than repeating a sentence.
alter table coupons add column if not exists automatic boolean not null default false;

-- How many items the headline price covers, and what each one after that
-- costs. "2,000 for three, 500 an item after" is still one price somebody can
-- say out loud, and it stops one person filling the boot for the price of a
-- pizza without a cliff where the offer suddenly stops applying.
--
-- Blank included_items means truly flat, however much they order.
alter table coupons add column if not exists included_items int;
alter table coupons add column if not exists extra_per_item int not null default 0
  check (extra_per_item >= 0);

-- Which same day windows it is good for, as the hour each one starts, comma
-- separated: "12,15". Empty means every window, and a run is not a window so
-- runs are unaffected by this.
--
-- The hour rather than a time: the windows on offer slide through the day as
-- it gets late, so anything fixed to an instant would stop matching by two
-- o'clock. An order belongs to a window if its delivery hour falls inside it.
alter table coupons add column if not exists windows text not null default '';

-- A promotion in a group: split, but never below this each.
--
-- Two thousand each was more than most of them pay today, so the group would
-- simply not use it. Split with a floor keeps the reason to bring somebody:
