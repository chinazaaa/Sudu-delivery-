-- A line of what actually happened, left at the counter for the shop.
--
-- About one stop in ten the counter is out of something. The customer
-- almost always says "give me something else for the same money", and the
-- shop then has real work to do: swap the line, so what sold is what the
-- brand figures count, and so the receipt and the order agree.
--
-- That work is not the driver's. She is standing at a till with a bag in
-- one hand; asking her to re-pick an item, reprice it and re-save an order
-- is how a sheet stops being used. So she writes one sentence and carries
-- on, and the note is the shop's signal that this run needs ten minutes
-- afterwards.
--
-- Its own table rather than a column on counter_spend, which is where the
-- price for a line already lives. A blank price there means "the menu was
-- right" and deletes the row, and a rule that quietly deletes a note
-- somebody wrote at a counter is the wrong kind of clever.
create table if not exists run_notes (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references batches (id) on delete cascade,
  -- The counter line it is about, keyed exactly as the run sheet groups
  -- them, so a note and its line are the same line by construction.
  line_key text not null,
  -- What the line is called, kept as it was written. The key carries the
  -- name already, but reading a key is not reading a sentence, and this
  -- is read by somebody deciding what to fix.
  said_about text not null default '',
  said text not null,
  created_at timestamptz not null default now(),
  -- When the shop put it right. Null is the whole point of the table: it
  -- is the list of what still needs doing.
  done_at timestamptz
);

create index if not exists run_notes_batch_idx on run_notes (batch_id);
create unique index if not exists run_notes_line_idx on run_notes (batch_id, line_key);

comment on table run_notes is
  'What happened at a counter, written by whoever was there, for the shop to put right afterwards. Null done_at means it still needs doing.';

-- A pause between wrong admin passwords.
--
-- A customer's four digit PIN already gets five tries and then a quarter
-- of an hour's rest. The admin password, which opens the whole shop, got
-- nothing: it could be guessed as fast as a machine could ask.
--
-- One row, because there is one password. Counting per address would be
-- kinder to the owner and useless against the attack, since the address a
-- request claims to come from is a header.
--
-- Deliberately a pause rather than a lockout. There is one admin, and
-- somebody hammering the login must not be able to shut the shop's owner
-- out of her own board on a Saturday evening. Five wrong tries buys sixty
-- seconds, which is nothing to a person who mistyped and ruinous to a
-- machine: it caps guessing at five a minute instead of thousands.
create table if not exists admin_gate (
  id boolean primary key default true,
  fails integer not null default 0,
  locked_until timestamptz,
  constraint admin_gate_one_row check (id)
);

insert into admin_gate (id, fails) values (true, 0) on conflict (id) do nothing;

comment on table admin_gate is
  'How many admin passwords have been got wrong in a row, and until when the next try must wait. One row.';

-- Like every other table here. Nothing but the server's own key ever
-- reaches this, but a table outside the rule is a table somebody has to
-- remember is outside the rule.
alter table admin_gate enable row level security;

-- What a thing costs at the counter, beside what it sells for.
--
-- The menu held one price, which is what the customer pays. What the
-- counter charges for the same thing was nowhere, so the shop's margin on
-- food could only ever be learned afterwards, by typing a receipt into the
-- run sheet, and until somebody did that every kitchen figure was the menu
-- compared with itself.
--
-- Selling price stays where it is. price_food is what a customer is
-- charged and what every order, every total and every figure already
-- reads; moving it would be a rewrite of the whole shop to gain nothing.
-- The cost sits beside it, and admin works out the selling price from it
-- so the two stay in step when a counter puts its prices up.
alter table menu_items
  add column if not exists price_cost integer;

comment on column menu_items.price_cost is
  'What this costs at the counter, before the shop''s markup. Null means nobody has said.';

-- Whether anybody has actually checked it.
--
-- The backfill below is arithmetic, not knowledge: it assumes every price
-- on the menu is the counter''s with fifteen per cent on, which is written
-- down for The Place and for Pitakwa and is a guess everywhere else.
-- Chicken Republic''s spaghetti at 2,100 works back to 1,826, which is not
-- a number a restaurant charges.
--
-- A wrong cost price is worse than an empty one. It makes every margin
-- confidently wrong and nothing looks broken, so the guess has to be able
-- to say it is a guess, and the shop has to be able to see what it has
-- actually confirmed.
alter table menu_items
  add column if not exists cost_confirmed boolean not null default false;

comment on column menu_items.cost_confirmed is
  'True once somebody has seen this cost on a receipt or a counter''s own menu. False means it was worked back from the selling price and is a guess.';

-- The markup, in one place, editable without a deploy.
alter table settings
  add column if not exists food_markup numeric not null default 15;

comment on column settings.food_markup is
  'Per cent added to a counter price to get the menu price. Fifteen is what the shop has used.';

-- Worked back from what is already on the menu, so there is something to
-- correct rather than four hundred empty boxes. Every one of them lands
-- unconfirmed.
update menu_items
set price_cost = round(price_food / 1.15)
where price_food > 0 and price_cost is null;
