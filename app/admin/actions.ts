/**
 * A notification to everybody who has the app and still wants to hear from us.
 *
 * Where it lands matters as much as what it says: "new deal at Domino's" that
 * opens the whole shop makes somebody do the finding themselves, which is the
 * moment most of them stop. So the destination is picked here, and travels
 * with the message.
 */
export async function sendDealPush(
  _prev: DealPushState,
  form: FormData
): Promise<DealPushState> {
  await assertAdmin();

  const title = String(form.get("title") ?? "").trim().slice(0, 80);
  const body = String(form.get("body") ?? "").trim().slice(0, 180);
  if (title.length < 3) return { error: "Give it a title.", sent: null };
  if (body.length < 3) return { error: "Give it a line of text.", sent: null };

  const where = String(form.get("restaurant") ?? "").trim();
  const category = String(form.get("category") ?? "").trim();

  // Only ever one of ours, built here rather than typed, so a stray paste
  // cannot send everybody somewhere off the shop. The prefix says which
  // kind of thing was picked, because they all come off one list: whoever
  // is sending this is choosing where it lands, not what sort of place it
  // is.
  const path = where.startsWith("occasion:")
    ? `/occasions/${where.slice(9)}`
    : where.startsWith("link:")
      ? `/c/${where.slice(5)}`
      : where === "skincare"
        ? "/skincare"
        : where
          ? `/r/${where}${category ? `?category=${category}` : ""}`
          : "/";

  const result = await pushDeal({ title, body, path });
  if (result.of === 0) {
    return { error: "No phone has the app with deals switched on yet.", sent: null };
  }

  revalidatePath("/admin/notifications");
  return { error: null, sent: result.sent };
}

/**
 * Moving one order onto another run, by hand.
 *
 * Somebody pays after the cut off. The food for that run has been bought, so
 * their money is sitting against a car that has gone, and the only honest
 * answer is the next one: a run later today, or a car of its own within the
 * three hours it takes to fetch and drive. That is a decision about a person
 * rather than a rule, which is why it is a button here and not a job that
 * runs at night, and why the message telling them is written by hand.
 *
 * A time rather than a run makes the car first, exactly as a same day order
 * does, and then moves them into it.
 */
export async function moveOrderToAnother(form: FormData): Promise<void> {
  await assertAdmin();

  const orderId = String(form.get("order_id") ?? "");
  const going = String(form.get("going") ?? "");
  if (orderId === "" || going === "") return;

  let batchId = going.startsWith("run:") ? going.slice(4) : "";

  if (batchId === "") {
    // A window of its own. The label is what the customer sees on their
    // order, so it is said the way every other window is said.
    const car = await createSameDayBatch({
      deliverAt: going,
      label: windowPhrase(going).replace(/^./, (one) => one.toUpperCase()),
    });
    if (!car) {
      redirect(`/admin/orders/${orderId}?moved=Could+not+make+that+car.`);
    }
    batchId = car.id;
  }

  // By hand, so the rules that stop a customer moving themselves do not
  // apply: this is the person who bought the food deciding where it goes.
  const result = await moveOrder(orderId, batchId, true);
  revalidatePath("/admin", "layout");
  redirect(
    `/admin/orders/${orderId}?moved=${encodeURIComponent(
      result.ok ? "Moved. Tell them which run they are on now." : result.error
    )}`
  );
}

/**
 * A whole catalogue, in from the file a shop platform exported.
 *
 * Two thousand products is not something anybody types in, and it is not
 * something anybody wants to do twice, so this is safe to run again: a
 * product already there by name keeps its id, its picture and anything that
 * has been changed about it by hand. What comes in is the price, the brand
 * and the shelf it sits on.
 *
 * Anything the file does not mention is left alone rather than deleted. A
 * shorter export is a shorter export, not an instruction to empty the shop.
 */
export async function importSkincare(
  _prev: { done: string; error: string },
  form: FormData
): Promise<{ done: string; error: string }> {
  await assertAdmin();

  const file = form.get("csv");
  const text =
    file instanceof File && file.size > 0
      ? await file.text()
      : String(form.get("pasted") ?? "");

  const { products, skipped } = parseCatalogue(text);
  if (products.length === 0) {
    return {
      done: "",
      error:
        "Nothing to import. It wants a file with a title and a price on every " +
        "row, and a header naming its columns.",
    };
  }

  // The shop itself. One row, marked skincare, which is what keeps two
  // thousand products out of a food menu.
  const shopName = String(form.get("shop_name") ?? "").trim() || "Skincare";
  const { data: existing } = await db()
    .from("restaurants")
    .select("id")
    .eq("kind", "skincare")
    .limit(1);

  let shopId = ((existing ?? [])[0]?.id as string) ?? "";
  if (shopId === "") {
    const { data, error } = await db()
      .from("restaurants")
      .insert({
        name: shopName,
        slug: "skincare",
        address: "",
        closes_at: "23:59",
        active: true,
        sort_order: 99,
        logo_url: "",
        banner_url: "",
        brand_hex: "",
        kind: "skincare",
      })
      .select("id")
      .single();
    if (error || !data) {
      return { done: "", error: error?.message ?? "Could not make the shop." };
    }
    shopId = data.id as string;
  }

  const { added, changed, sections, choices, error } = await putCatalogue(shopId, products);
  if (error !== "") return { done: `${added} in, then it stopped.`, error };

  revalidatePath("/admin", "layout");
  revalidatePath("/skincare");

  return { done: said(added, changed, sections, skipped, choices), error: "" };
}

/**
 * How an import went, in the words somebody running a shop would use.
 *
 * The skipped count is named rather than buried: a file where half the rows
 * had no price is a file worth looking at again, and a silent import of the
 * other half is how a menu ends up missing things nobody notices for a week.
 */
function said(
  added: number,
  changed: number,
  sections: number,
  skipped: number,
  choices = 0
): string {
  return (
    `${added} new, ${changed} updated, ${sections} section${sections === 1 ? "" : "s"}` +
    (choices > 0 ? `, ${choices} choice${choices === 1 ? "" : "s"} to pick from` : "") +
    (skipped > 0
      ? `. ${skipped} row${skipped === 1 ? " was" : "s were"} left out for having no ` +
        "price: an export writes \"Out of stock\" where the price goes, and a " +
        "product with no price is not one anybody can order."
      : ".")
  );
}

/**
 * A catalogue put into one restaurant, safely to run again.
 *
 * What is already there by name keeps its id, its photograph and anything
 * changed by hand; what comes in is the price, the section and whether the
 * shop has it. Nothing is deleted, because a shorter file is a shorter file
 * and not an instruction to empty a menu.
 */
async function putCatalogue(
  shopId: string,
  products: ImportedProduct[]
): Promise<{
  added: number;
  changed: number;
  sections: number;
  /** How many choices were hung off the dishes, for the line it reports. */
  choices: number;
  error: string;
}> {
  // The shelves, by name. Everything already there keeps its id so that
  // anything filed under it stays filed under it.
  const wantedSections = [
    ...new Set(products.flatMap((one) => (one.shelves.length > 0 ? one.shelves : [one.category]))),
  ].filter(Boolean);
  const { data: sections } = await db()
    .from("menu_categories")
    .select("id, name")
    .eq("restaurant_id", shopId);
  const sectionId = new Map(
    ((sections ?? []) as { id: string; name: string }[]).map((one) => [one.name, one.id])
  );

  const newSections = wantedSections.filter((name) => !sectionId.has(name));
  if (newSections.length > 0) {
    const { data: made } = await db()
      .from("menu_categories")
      .insert(
        newSections.map((name, index) => ({
          restaurant_id: shopId,
          name,
          sort_order: sectionId.size + index,
        }))
      )
      .select("id, name");
    for (const one of ((made ?? []) as { id: string; name: string }[])) {
      sectionId.set(one.name, one.id);
    }
  }

  // What is already on the shelf, so running this again changes prices
  // rather than making a second copy of everything.
  //
  // Matched on the name and the section together, because one kitchen sells
  // the same dish as a plate and as a sharing tray at five times the price,
  // and by name alone the second one overwrites the first. Where a name
  // appears only once in the whole shop the section is not asked for, so a
  // catalogue imported before this, or one whose sections have been tidied
  // by hand since, still matches itself rather than arriving twice.
  const { data: already } = await db()
    .from("menu_items")
    .select("id, name, category_id")
    .eq("restaurant_id", shopId);
  const rowsThere = (already ?? []) as {
    id: string;
    name: string;
    category_id: string | null;
  }[];

  const byNameAndSection = new Map(
    rowsThere.map((one) => [`${one.name.toLowerCase()}|${one.category_id ?? ""}`, one.id])
  );
  const timesNamed = new Map<string, number>();
  for (const one of rowsThere) {
    const name = one.name.toLowerCase();
    timesNamed.set(name, (timesNamed.get(name) ?? 0) + 1);
  }
  const byName = new Map(
    rowsThere
      .filter((one) => timesNamed.get(one.name.toLowerCase()) === 1)
      .map((one) => [one.name.toLowerCase(), one.id])
  );

  const idOf = (name: string, categoryId: string | null): string | undefined =>
    byNameAndSection.get(`${name.toLowerCase()}|${categoryId ?? ""}`) ??
    byName.get(name.toLowerCase());

  const rows = products.map((one, index) => ({
    restaurant_id: shopId,
    category_id: one.category ? (sectionId.get(one.category) ?? null) : null,
    name: one.name,
    price_food: one.price,
    // What the menu says it is. Only ever written on the way in, so anything
    // rewritten by hand afterwards survives the next import.
    description: one.description,
    // The picture the export carried, so the shelf is not two thousand grey
    // boxes on the first day. Photographs uploaded later replace it.
    image_url: one.imageUrl,
    image_file: one.imageFile,
    shelves: shelfText(one.shelves),
    brand: one.brand,
    // What the shop says it has. Anything not plainly in stock is off the
    // shelf rather than something somebody orders and then has to be rung
    // about, and a later import puts it back the moment it returns.
    available: one.available,
    sort_order: index,
  }));

  // The kitchen's questions, kept beside the rows so they can be written once
  // the dishes have ids.
  const askedOn = new Map(rows.map((row, index) => [row, products[index].options]));

  // In chunks, because a single insert of two thousand rows is one request
  // that either works or loses the lot, and this way a failure says which
  // part of the file it got to.
  let added = 0;
  let changed = 0;
  const SIZE = 200;

  // Which dish each row became, so its options can be hung off it.
  const landedOn = new Map<(typeof rows)[number], string>();

  for (let at = 0; at < rows.length; at += SIZE) {
    const chunk = rows.slice(at, at + SIZE);
    const fresh = chunk.filter((row) => idOf(row.name, row.category_id) === undefined);
    const known = chunk.filter((row) => idOf(row.name, row.category_id) !== undefined);
    for (const row of known) landedOn.set(row, idOf(row.name, row.category_id)!);

    if (fresh.length > 0) {
      const { data: made, error } = await db()
        .from("menu_items")
        .insert(fresh)
        .select("id, name, category_id");
      if (error) {
        return {
          added,
          changed,
          sections: wantedSections.length,
          choices: 0,
          error: `${error.message}. Nothing after ${chunk[0].name} went in.`,
        };
      }
      // Matched back by name and section, which is the pair that told them
      // apart going in.
      const fromInsert = new Map(
        ((made ?? []) as { id: string; name: string; category_id: string | null }[]).map(
          (one) => [`${one.name.toLowerCase()}|${one.category_id ?? ""}`, one.id]
        )
      );
      for (const row of fresh) {
        const id = fromInsert.get(`${row.name.toLowerCase()}|${row.category_id ?? ""}`);
        if (id) landedOn.set(row, id);
      }
      added += fresh.length;
    }

    // What is already there, in one request rather than one each. A second
    // import used to be two thousand round trips, which is not a slow import,
    // it is one that never finishes.
    //
    // Only the columns named here are written, so a photograph uploaded
    // afterwards and anything typed in by hand survive being re-imported.
    if (known.length > 0) {
      const { error } = await db()
        .from("menu_items")
        .upsert(
          known.map((row) => ({
            id: landedOn.get(row)!,
            restaurant_id: row.restaurant_id,
            name: row.name,
            price_food: row.price_food,
            category_id: row.category_id,
            brand: row.brand,
            image_file: row.image_file,
            shelves: row.shelves,
            available: row.available,
          })),
          { onConflict: "id" }
        );
      if (error) {
        return {
          added,
          changed,
          sections: wantedSections.length,
          choices: 0,
          error: `${error.message}. Nothing after ${chunk[0].name} was touched.`,
        };
      }
      changed += known.length;
    }
  }

  const picks = await putOptions(rows, askedOn, landedOn);
  if (picks.error !== "") {
    return { added, changed, sections: wantedSections.length, choices: 0, error: picks.error };
  }

  return {
    added,
    changed,
    sections: wantedSections.length,
    choices: picks.choices,
    error: "",
  };
}

/**
 * The questions a dish asks, written under the dishes that have just landed.
 *
 * A restaurant export carries them and the shop cannot sell without them: a
 * burrito bowl with no rice choice is a dish nobody can order the way they
 * want it, and a spice level nobody was asked is an argument at the door.
 *
 * Only ever for a dish that has none. A second import must not wipe the
 * groups somebody tidied by hand, and re-running this is how a price list is
 * kept up to date, so it has to be safe to run every week.
 */
async function putOptions(
  rows: { name: string; category_id: string | null }[],
  askedOn: Map<(typeof rows)[number], ImportedGroup[]>,
  landedOn: Map<(typeof rows)[number], string>
): Promise<{ choices: number; error: string }> {
  const wanted = rows
    .map((row) => ({ id: landedOn.get(row), groups: askedOn.get(row) ?? [] }))
    .filter((one): one is { id: string; groups: ImportedGroup[] } =>
      Boolean(one.id) && one.groups.length > 0
    );
  if (wanted.length === 0) return { choices: 0, error: "" };

  const { data: existing } = await db()
    .from("item_option_groups")
    .select("menu_item_id")
    .in("menu_item_id", wanted.map((one) => one.id));
  const answered = new Set(
    ((existing ?? []) as { menu_item_id: string }[]).map((one) => one.menu_item_id)
  );

  const fresh = wanted.filter((one) => !answered.has(one.id));
  if (fresh.length === 0) return { choices: 0, error: "" };

  const groupRows = fresh.flatMap((one) =>
    one.groups.map((group, index) => ({
      menu_item_id: one.id,
      name: group.name,
      required: group.required,
      max_select: group.max,
      sort_order: index,
    }))
  );

  const { data: madeGroups, error: groupError } = await db()
    .from("item_option_groups")
    .insert(groupRows)
    .select("id, menu_item_id, name");
  if (groupError) {
    return { choices: 0, error: `The dishes went in, but their choices did not: ${groupError.message}` };
  }

  const groupId = new Map(
    ((madeGroups ?? []) as { id: string; menu_item_id: string; name: string }[]).map((one) => [
      `${one.menu_item_id}|${one.name}`,
      one.id,
    ])
  );

  const choiceRows = fresh.flatMap((one) =>
    one.groups.flatMap((group) => {
      const id = groupId.get(`${one.id}|${group.name}`);
      if (!id) return [];
      return group.choices.map((choice, index) => ({
        group_id: id,
        name: choice.name,
        price_delta: choice.price,
        available: choice.available,
        sort_order: index,
      }));
    })
  );
  if (choiceRows.length === 0) return { choices: 0, error: "" };

  // In chunks: a menu of sixty dishes carries fifteen hundred choices, which
  // is not one request anybody should bet the import on.
  const SIZE = 500;
  for (let at = 0; at < choiceRows.length; at += SIZE) {
    const { error } = await db()
      .from("item_options")
      .insert(choiceRows.slice(at, at + SIZE));
    if (error) {
      return { choices: 0, error: `The dishes went in, but their choices did not: ${error.message}` };
    }
  }

  return { choices: choiceRows.length, error: "" };
}

/**
 * Shelves nothing is on any more.
 *
 * An import makes a shelf for every collection the file names, and the next
 * file, or a hand edit, leaves some of them standing there empty. They are
 * only ever deleted when nothing is on them and nothing is filed under them,
 * which is checked here rather than trusted from the form: a page can be
 * stale by the time a button is pressed, and a shelf deleted out from under
 * two hundred products is a filing job nobody wants.
 */
export async function deleteEmptyShelves(form: FormData): Promise<void> {
  await assertAdmin();

  const asked = new Set(form.getAll("shelf_id").map(String).filter(Boolean));
  if (asked.size === 0) return;

  const empty = (await skincareShelves())
    .filter((one) => one.items === 0 && one.filed === 0)
    .map((one) => one.id)
    .filter((id) => asked.has(id));

  if (empty.length > 0) {
    await db().from("menu_categories").delete().in("id", empty);
  }

  revalidatePath("/admin", "layout");
  revalidatePath("/skincare");
}

/**
 * The skincare settings, saved without taking the page down.
 *
 * The general settings action throws when the database has not got a column
 * yet, and a throw from a server action is the error boundary: a yellow
 * exclamation mark and a minified React number where the sentence explaining
 * what to do should be. These columns are the newest in the shop, so this is
 * exactly the form where that happens, and it hands back what went wrong
 * instead of losing it.
 */
export async function saveSkincare(
  _prev: { done: string; error: string },
  form: FormData
): Promise<{ done: string; error: string }> {
  await assertAdmin();

  const fields = [
    "skincare_on",
    "skincare_fee",
    "skincare_day",
    "skincare_cut_off",
    "skincare_window",
    "skincare_blurb",
    "skincare_bands",
    "skincare_promise",
  ] as const;

  const patch: Record<string, string> = {};
  for (const field of fields) {
    const value = form.get(field);
    if (value !== null) patch[field] = String(value).trim();
  }
  if (Object.keys(patch).length === 0) return { done: "", error: "" };

  const write = (fields: Record<string, string>) =>
    db()
      .from("settings")
      .update({ ...fields, updated_at: new Date().toISOString() })
      .eq("id", true);

  let { error } = await write(patch);

  // One column the database has not been given yet rejects the whole update,
  // so the day and the cut off would fail to save because of a ladder added
  // later. The unknown one is dropped and the rest saved, and what did not
  // save is said plainly rather than guessed at.
  const missing: string[] = [];
  while (error && missing.length < fields.length) {
    const named = fields.find((field) => field in patch && error!.message.includes(field));
    if (!named) break;
    missing.push(named);
    delete patch[named];
    if (Object.keys(patch).length === 0) break;
    ({ error } = await write(patch));
  }

  revalidatePath("/admin", "layout");
  revalidatePath("/skincare");
  revalidatePath("/", "layout");

  if (error) {
    return {
      done: "",
      error: `Could not save that: ${error.message}. If it names a column, run supabase/update.sql in Supabase.`,
    };
  }
  if (missing.length > 0) {
    return {
      done: "",
      error:
        `Saved everything except ${missing.join(", ")}: the database has not got ` +
        "that column yet. Run supabase/update.sql in Supabase and save again.",
    };
  }
  return { done: "Saved.", error: "" };
}

/**
 * A catalogue into an ordinary restaurant.
 *
 * The same import the skincare shelf uses, pointed at a menu instead. Two
 * hundred products from a market is not something anybody types in either,
 * and the difference between a shelf and a menu is which restaurant row they
 * are filed under, not how they arrive.
 */
export async function importCatalogue(
  _prev: { done: string; error: string },
  form: FormData
): Promise<{ done: string; error: string }> {
  await assertAdmin();

  const shopId = String(form.get("restaurant_id") ?? "");
  if (shopId === "") return { done: "", error: "No restaurant to put it in." };

  const file = form.get("csv");
  const text =
    file instanceof File && file.size > 0
      ? await file.text()
      : String(form.get("pasted") ?? "");

  const { products, skipped } = parseCatalogue(text);
  if (products.length === 0) {
    return {
      done: "",
      error:
        "Nothing to import. It wants a name and a price on every row, and a " +
        "header naming the columns: category, name, price, image_url.",
    };
  }

  const { added, changed, sections, choices, error } = await putCatalogue(shopId, products);
  if (error !== "") return { done: `${added} in, then it stopped.`, error };

  revalidatePath("/admin", "layout");
  updateTag("menu");
  revalidatePath("/", "layout");

  return { done: said(added, changed, sections, skipped, choices), error: "" };
}

/**
 * Who a customer belongs to, set by hand.
 *
 * The order path writes this once, on a first order, and never touches it
 * again: that is what makes a promoter's commission lifetime, and it is why
 * nothing else in the shop is allowed to change it. This is the deliberate
 * exception, for the customers who ordered before the question was asked and
 * whose promoter everybody already knows.
 *
 * Moving somebody moves every order they have ever placed, so it is a
 * decision about money rather than a tidy-up.
 */
export async function setCustomerPromoter(form: FormData): Promise<void> {
  await assertAdmin();

  const phone = normalisePhone(String(form.get("phone") ?? ""));
  if (!phone) return;

  const code = String(form.get("promoter_code") ?? "").trim();
  // Nobody is a real answer, and a code that is not a promoter is not.
  const belongs = code !== "" && (await realPromoter(code)) ? code : null;

  await db().from("customers").update({ promoter_code: belongs }).eq("phone", phone);

  revalidatePath("/admin", "layout");
}

/**
 * A promoter's code, changed without losing who they brought.
 *
 * The code is the key: a customer carries it for life, an order carries it,
 * a payout is filed under it. The database moves all of that itself, so this
 * is one update, but it is still the one thing on that page that can break
 * somebody's earnings, which is why it is its own form and says what it is
 * about to do.
 *
 * Their sign-in changes with it, so whoever renames them has to send them
 * their details again.
 */
export async function renamePromoter(
  _prev: { done: string; error: string },
  form: FormData
): Promise<{ done: string; error: string }> {
  await assertAdmin();

  const from = String(form.get("code") ?? "").trim();
  const to = String(form.get("new_code") ?? "").trim().toUpperCase();
  if (from === "" || to === "") return { done: "", error: "" };
  if (from === to) return { done: "", error: "That is the code they already have." };

  // Letters and numbers, because it is typed into a sign-in box by somebody
  // reading it off a WhatsApp message.
  if (!/^[A-Z0-9]{2,20}$/.test(to)) {
    return {
      done: "",
      error: "A code is 2 to 20 letters or numbers, with nothing else in it.",
    };
  }

  const { data: taken } = await db()
    .from("promoters")
    .select("code")
    .eq("code", to)
    .maybeSingle();
  if (taken) return { done: "", error: `${to} belongs to somebody else already.` };

  const { error } = await db().from("promoters").update({ code: to }).eq("code", from);
  if (error) {
    return {
      done: "",
      error:
        `Could not rename that: ${error.message}. If it mentions a constraint or a key, ` +
        "run supabase/update.sql in Supabase and try again.",
    };
  }

  revalidatePath("/admin", "layout");
  revalidatePath("/promoter");

  return {
    done: `${from} is now ${to}. Everyone they brought came with it. Send them their details again, because their sign-in changed.`,
    error: "",
  };
}
