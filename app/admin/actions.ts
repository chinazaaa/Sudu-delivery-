/**
 * Close the books on a run.
 *
 * Checked again here rather than trusted from the page: the page can be old,
 * and a run settled with money still outstanding is a run nobody will think
 * to look at again.
 */
export async function settleRun(form: FormData): Promise<void> {
  await assertAdmin();
  const id = String(form.get("batch_id"));

  const sheet = await batchSheet(id);
  if (!sheet) return;

  const open = stillOpen(sheet);
  if (open.length > 0) {
    throw new Error(`That run is not finished: ${open.join(" ")}`);
  }

  // A run where nothing was typed at the counter is either a run that cost
  // exactly the menu price or one nobody checked, and the difference is
  // money. Somebody has to say which.
  if (
    sheet.summary.reconciled.lines === 0 &&
    sheet.summary.reconciled.of > 0 &&
    form.get("counter_checked") !== "on"
  ) {
    throw new Error(
      "Nothing was typed at the counter on that run. Say the prices were the menu prices first."
    );
  }

  await db()
    .from("batches")
    .update({ settled_at: new Date().toISOString() })
    .eq("id", id);

  revalidatePath("/admin", "layout");
}

