type GroupDraft = {
  name: string;
  required: boolean;
  maxSelect: number;
  options: { name: string; priceDelta: number }[];
};

/** Writes a builder's option groups onto an item, in the order they were typed. */
async function saveGroups(itemId: string, json: string): Promise<void> {
  let groups: GroupDraft[] = [];
  try {
    groups = JSON.parse(json) as GroupDraft[];
  } catch {
    return; // A malformed draft is not worth failing the item over.
  }

  for (const [index, group] of groups.entries()) {
    const groupName = String(group.name ?? "").trim();
    if (!groupName) continue;

    const { data: saved } = await db()
      .from("item_option_groups")
      .insert({
        menu_item_id: itemId,
        name: groupName,
        required: Boolean(group.required),
        max_select: Math.max(1, Number(group.maxSelect) || 1),
        sort_order: index * 10,
      })
      .select("id")
      .single();
    if (!saved) continue;

    const options = (group.options ?? [])
      .map((option, position) => ({
        group_id: saved.id as string,
        name: String(option.name ?? "").trim(),
        price_delta: Math.round(Number(option.priceDelta) || 0),
        sort_order: position * 10,
      }))
      .filter((option) => option.name.length > 0);

    if (options.length > 0) await db().from("item_options").insert(options);
  }
}

