/**
 * Manual "mark paid". The transfer is matched by the phone number in the
 * narration. This is replaced by a Paystack webhook once reconciliation stops
 * being trivial (brief §13), which is why payment_ref exists from day one.
 */
export async function markPaid(form: FormData): Promise<void> {
  await assertAdmin();
  const id = String(form.get("order_id"));
  const ref = String(form.get("payment_ref") ?? "").trim();

  await db()
    .from("orders")
    .update({
      status: "paid",
      paid_at: new Date().toISOString(),
      payment_ref: ref || null,
    })
    .eq("id", id);

  // If they have the app, tell them. Not awaited by anything that matters,
  // and a failure here leaves the order paid all the same.
  void (async () => {
    try {
      const { data } = await db()
        .from("orders")
        .select("customer_phone, customer_name")
        .eq("id", id)
        .maybeSingle();
      const row = data as { customer_phone: string; customer_name: string } | null;
      if (!row) return;

      await pushToPhone(row.customer_phone, {
        title: "Payment confirmed",
        body: `Thanks ${row.customer_name.split(" ")[0]}. Your food is on this run.`,
        path: `/o/${id}`,
      });
    } catch {
      /* Nothing said is better than an order that would not save. */
    }
  })();

  revalidatePath("/admin", "layout");
}

