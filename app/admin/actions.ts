/**
 * What things actually cost at the counter, line by line.
 *
 * Only the lines somebody typed something into. Most of the time one or two
 * prices moved and the rest were exactly the menu, so a blank means "the menu
 * was right" rather than "this was free", and clearing a figure puts that
 * line back to the menu price.
 */
export async function setCounterSpend(form: FormData): Promise<void> {
  await assertAdmin();
  const batchId = String(form.get("batch_id") ?? "");
  if (!batchId) return;

  const keys = form.getAll("line_key").map(String);
  const typed = form.getAll("paid").map(String);

  for (const [index, key] of keys.entries()) {
    const raw = (typed[index] ?? "").trim();
    const value = Math.round(Number(raw));

    if (raw === "" || !Number.isFinite(value) || value < 0) {
      // Back to the menu price for that one thing.
      await db()
        .from("counter_spend")
        .delete()
        .eq("batch_id", batchId)
        .eq("line_key", key);
      continue;
    }

    // What the customer handed back, when they were asked to cover a gap.
    // Blank is none, which is the usual answer.
    const backRaw = String(form.getAll("recovered")[index] ?? "").trim();
    const back = Math.round(Number(backRaw));
    const recovered = backRaw !== "" && Number.isFinite(back) && back > 0 ? back : 0;

    await db()
      .from("counter_spend")
      .upsert(
        {
          batch_id: batchId,
          line_key: key,
          paid: value,
          recovered,
          updated_at: new Date().toISOString(),
        },
        { onConflict: "batch_id,line_key" }
      );
  }

  revalidatePath("/admin", "layout");
}

/**
 * Put a menu price up, because a counter really has put it up.
 *
 * Only ever upward, and only from a figure somebody typed after paying it.
 * A counter charging less is usually a promo or a good mood on the day, and
 * following it down would drop the shop's own price on the strength of one
 * afternoon. Charging more tends to stay charged, and a menu that is behind
 * loses money on every order until somebody notices.
 *
 * Never automatic. The figure came from a phone at a counter, so a slipped
 * digit would otherwise raise a price nobody meant to raise.
 */
export async function raiseMenuPrice(form: FormData): Promise<void> {
  await assertAdmin();

  const itemId = String(form.get("item_id") ?? "");
  const by = Math.round(Number(form.get("by") ?? 0));
  if (!itemId || !Number.isFinite(by) || by <= 0) return;

  const { data: item } = await db()
    .from("menu_items")
    .select("price_food")
    .eq("id", itemId)
    .maybeSingle();
  if (!item) return;

  await db()
    .from("menu_items")
    .update({ price_food: (item.price_food as number) + by })
    .eq("id", itemId);

  updateTag("menu");
  revalidatePath("/admin", "layout");
  revalidatePath("/", "layout");
}

/**
 * Move a same day car into another window.
 *
 * Somebody asks for three to six, you ring them, and they are happy to have
 * it at lunchtime instead. That turns two shopping trips into one, and the
 * only way to say so was to have no way to say so.
 *
 * Moving it is all that is needed: trips are clustered by the time asked for,
 * so a car moved into another window joins that trip on its own.
 *
 * The customer is not told by this. It comes from a phone call, so the
 * agreement already happened; changing it here is writing down what was said.
 */
export async function moveSameDayCar(form: FormData): Promise<void> {
  await assertAdmin();

  const id = String(form.get("batch_id") ?? "");
  const at = String(form.get("deliver_at") ?? "");
  if (!id || !at) return;

  const { data: batch } = await db()
    .from("batches")
    .select("kind, stage")
    .eq("id", id)
    .maybeSingle();

  // Only a car, and only one that has not been bought for yet: moving a
  // delivery after the food is in the boot moves nothing but the record.
  if (!batch || batch.kind !== "same_day") return;
  if (batch.stage !== "ordering") return;

  const slot = (await deliverySlots(new Date(), await hoursByDay())).find(
    (one) => one.at === at
  );
  if (!slot) return;

  await db()
    .from("batches")
    .update({
      deliver_at: slot.at,
      delivery_window_text: slot.label,
      run_date: lagosToday(new Date(slot.at)),
      // The enum only knows the two, and nothing reads it on a same day car.
      slot: new Date(slot.at).getUTCHours() >= 16 ? "night" : "afternoon",
    })
    .eq("id", id);

  revalidatePath("/admin", "layout");
  revalidatePath("/");
}

export async function setRunCosts(form: FormData): Promise<void> {
  await assertAdmin();
  const money = (field: string) => {
    const value = Math.round(Number(form.get(field) ?? 0));
    return Number.isFinite(value) && value > 0 ? value : 0;
  };

  // The food is priced at the counter now, item by item, so this form no
  // longer carries a figure for the whole shop. Runs reconciled the old way
  // keep theirs: absent means leave it alone, not set it to nothing.
  const whole = form.has("food_spend") ? { food_spend: money("food_spend") } : {};

  const id = String(form.get("batch_id"));
  const costs = {
    fuel_cost: money("fuel_cost"),
    driver_cost: money("driver_cost"),
    other_cost: money("other_cost"),
    ...whole,
    cost_note: String(form.get("cost_note") ?? "").trim(),
  };

  // Transport is the newest of these. Naming a column the database has not
  // been given yet fails the whole update, which would lose the fuel and the
  // driver along with it, so it is tried and then dropped.
  const { error } = await db()
    .from("batches")
    .update({ ...costs, transport_cost: money("transport_cost") })
    .eq("id", id);
  if (error) await db().from("batches").update(costs).eq("id", id);

  revalidatePath("/admin", "layout");
}

/**
 * When a run lands and when it closes, changed after the run exists. A run
 * that slips by an hour has to be able to say so without being recreated.
 */
export async function updateRun(form: FormData): Promise<void> {
  await assertAdmin();
  const id = String(form.get("batch_id"));

  const { data: batch } = await db()
    .from("batches")
    .select("run_date, slot")
    .eq("id", id)
    .maybeSingle();
  if (!batch) return;

  const orders = await orderCount(id);
  // The day and the slot decide which orders belong where, so they only move
  // while the run is still empty. The window and the cut-off change any time.
  const runDate =
    orders === 0 && String(form.get("run_date") ?? "").trim()
      ? String(form.get("run_date")).trim()
      : (batch.run_date as string);
  const slot =
    orders === 0 && String(form.get("slot") ?? "")
      ? String(form.get("slot"))
      : (batch.slot as string);

  const patch: Record<string, string> = {
    run_date: runDate,
    slot,
    delivery_window_text: String(form.get("delivery_window_text") ?? "").trim(),
  };

  const time = String(form.get("cut_off_time") ?? "").trim();
  if (/^\d{2}:\d{2}$/.test(time)) {
    const [hour, minute] = time.split(":").map(Number);
    patch.cut_off_at = lagosInstant(runDate, hour, minute);
  }

  await db().from("batches").update(patch).eq("id", id);

  revalidatePath("/admin", "layout");
  updateTag("menu");
  revalidatePath("/", "layout");
}

/** One line of the weekly schedule: a day, a slot, a cut-off and a window. */
export async function saveScheduleRun(form: FormData): Promise<void> {
  await assertAdmin();
  const weekday = Number(form.get("weekday"));
  const slot = String(form.get("slot") ?? "afternoon");
  const cutOff = String(form.get("cut_off") ?? "").trim();
  if (!Number.isInteger(weekday) || weekday < 0 || weekday > 6) return;
  if (!/^\d{2}:\d{2}$/.test(cutOff)) return;

  const { error } = await db()
    .from("run_schedule")
    .upsert(
      {
        weekday,
        slot,
        cut_off: cutOff,
        window_text: String(form.get("window_text") ?? "").trim(),
        // Saving a time must not quietly bring a paused day back.
        active: form.get("active") !== "false",
      },
      { onConflict: "weekday,slot" }
    );
  if (error) throw new Error(`Could not save that day: ${error.message}`);

  // The runs already opened for that day follow the new time. Only ones still
  // to come, and only while nothing has been ordered on them: a run with
  // orders keeps the cut-off and the delivery time its customers were told.
  const windowText = String(form.get("window_text") ?? "").trim();
  const { data: rows } = await db()
    .from("batches")
    .select("id, run_date")
    .eq("slot", slot)
    .gte("run_date", lagosToday());

  // Midday UTC, so the day cannot slip either side of midnight.
  const sameDay = ((rows ?? []) as { id: string; run_date: string }[]).filter(
    (row) => new Date(`${row.run_date}T12:00:00Z`).getUTCDay() === weekday
  );

  if (sameDay.length > 0) {
    const ids = sameDay.map((row) => row.id);
    const { data: taken } = await db().from("orders").select("batch_id").in("batch_id", ids);
    const busy = new Set((taken ?? []).map((row) => row.batch_id as string));
    const [hour, minute] = cutOff.split(":").map(Number);

    for (const row of sameDay) {
      if (busy.has(row.id)) continue;
      await db()
        .from("batches")
        .update({
          cut_off_at: lagosInstant(row.run_date, hour, minute),
          ...(windowText ? { delivery_window_text: windowText } : {}),
        })
        .eq("id", row.id);
    }
  }

  revalidatePath("/admin", "layout");
}

/**
 * Removes a day from the schedule. Runs already opened for it are left alone:
 * they are deleted one at a time, and only while nothing has been ordered.
 */
export async function deleteScheduleRun(form: FormData): Promise<void> {
  await assertAdmin();
  const { error } = await db()
    .from("run_schedule")
    .delete()
    .eq("id", String(form.get("schedule_id")));
  // Saying nothing is how a Remove button that removes nothing goes unnoticed.
  if (error) throw new Error(`Could not remove that day: ${error.message}`);

  // The runs it already opened go with it, or Friday is off the schedule and
  // still on the shop, which is what "I deleted it and it is still there"
  // turned out to mean. Only ones still to come, and only while nothing has
  // been ordered on them: a run somebody has paid into is never swept away by
  // an edit to the week.
  const weekday = Number(form.get("weekday"));
  const slot = String(form.get("slot") ?? "");
  if (Number.isInteger(weekday) && slot) {
    const { data: rows } = await db()
      .from("batches")
      .select("id, run_date")
      .eq("slot", slot)
      .gte("run_date", lagosToday());

    // Midday UTC, so the day cannot slip either side of midnight.
    const sameDay = ((rows ?? []) as { id: string; run_date: string }[]).filter(
      (row) => new Date(`${row.run_date}T12:00:00Z`).getUTCDay() === weekday
    );

    if (sameDay.length > 0) {
      const ids = sameDay.map((row) => row.id);
      const { data: taken } = await db()
        .from("orders")
        .select("batch_id")
        .in("batch_id", ids);
      const busy = new Set((taken ?? []).map((row) => row.batch_id as string));
      const empty = ids.filter((id) => !busy.has(id));
      if (empty.length > 0) await db().from("batches").delete().in("id", empty);
    }
  }

  revalidatePath("/admin", "layout");
}

